package main

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
)

// attribute is a Terraform attribute that a generated function maps.
type attribute struct {
	name  string
	field string
	// enum is the sdk-go string enum type of the field, or empty for *string.
	enum string
	schemaField
}

// generate returns the formatted source of the spec's file.
func generate(spec mappingSpec, specDir string) ([]byte, error) {
	schemaPath := filepath.Join(specDir, spec.Schema.File)
	pkgName, schemaFields, err := readSchemaStruct(schemaPath, spec.Schema.Struct)
	if err != nil {
		return nil, err
	}
	sdkGo, err := loadSdkGoPackage(filepath.Dir(schemaPath), spec.SdkGo.Package)
	if err != nil {
		return nil, err
	}
	resolve := func(f mappingFunc) ([]attribute, error) {
		sdkGoFields, err := sdkGo.fields(f.Type)
		if err != nil {
			return nil, err
		}
		return resolveAttributes(f, spec.Schema.Struct, schemaFields, sdkGoFields)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/sdkgomapping. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n", pkgName)
	fmt.Fprintf(&b, "%s %q\n", spec.SdkGo.Name, spec.SdkGo.Package)
	fmt.Fprintf(&b, "%q\n)\n", "github.com/hashicorp/terraform-plugin-sdk/v2/helper/schema")
	for _, f := range spec.FromData {
		attributes, err := resolve(f)
		if err != nil {
			return nil, err
		}
		writeFromData(&b, spec.SdkGo.Name, f, attributes)
	}
	for _, f := range spec.ToData {
		attributes, err := resolve(f)
		if err != nil {
			return nil, err
		}
		writeToData(&b, spec.SdkGo.Name, f, attributes)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format the generated code: %w", err)
	}
	return src, nil
}

// resolveAttributes matches each attribute of f with its field in the schema struct and
// the field of the same Go name in the sdk-go struct.
func resolveAttributes(f mappingFunc, schemaStruct string,
	schemaFields map[string]schemaField, sdkGoFields map[string]sdkGoField,
) ([]attribute, error) {
	var attributes []attribute
	for _, name := range f.Attributes {
		sf, ok := schemaFields[name]
		if !ok {
			return nil, fmt.Errorf("%s: attribute %s is not in %s", f.Function, name, schemaStruct)
		}
		gf, ok := sdkGoFields[sf.goName]
		if !ok {
			return nil, fmt.Errorf("%s: attribute %s: %s has no field %s",
				f.Function, name, f.Type, sf.goName)
		}
		supported := gf.kind == sdkGoEnum && sf.kind != schemaUnsupported ||
			gf.kind == sdkGoStringPointer && sf.kind == schemaString
		if !supported {
			return nil, fmt.Errorf("%s: attribute %s: can't map %s.%s to %s.%s, only a "+
				"string to a *string or a string or named type to a string enum",
				f.Function, name, schemaStruct, sf.goName, f.Type, sf.goName)
		}
		attributes = append(attributes,
			attribute{name: name, field: sf.goName, enum: gf.enum, schemaField: sf})
	}
	return attributes, nil
}

// writeFromData writes a function that builds the sdk-go struct as
// common.DataToStructPointer and json.Marshal of the classic SDK's struct do: an empty
// attribute with omitempty is not sent, and every other attribute is.
func writeFromData(b *bytes.Buffer, sdkGo string, f mappingFunc, attributes []attribute) {
	fmt.Fprintf(b, "\n// %s returns the %s.%s for d.\n", f.Function, sdkGo, f.Type)
	fmt.Fprintf(b, "func %s(d *schema.ResourceData) %s.%s {\n", f.Function, sdkGo, f.Type)
	fmt.Fprintf(b, "r := %s.%s{\n", sdkGo, f.Type)
	for _, a := range attributes {
		get := fmt.Sprintf("d.Get(%q).(string)", a.name)
		switch {
		// sdk-go doesn't send an empty enum.
		case a.enum != "":
			fmt.Fprintf(b, "%s: %s.%s(%s),\n", a.field, sdkGo, a.enum, get)
		case !a.omitEmpty:
			fmt.Fprintf(b, "%s: new(%s),\n", a.field, get)
		}
	}
	b.WriteString("}\n")
	for _, a := range attributes {
		if a.enum == "" && a.omitEmpty {
			fmt.Fprintf(b, "if v := d.Get(%q).(string); v != \"\" {\nr.%s = &v\n}\n",
				a.name, a.field)
		}
	}
	b.WriteString("return r\n}\n")
}

// writeToData writes a function that sets the state from the sdk-go struct as
// common.StructToData does: it skips an empty optional attribute, and an attribute that
// is neither computed nor configured unless the resource is new, such as on import.
func writeToData(b *bytes.Buffer, sdkGo string, f mappingFunc, attributes []attribute) {
	fmt.Fprintf(b, "\n// %s sets d from v.\n", f.Function)
	fmt.Fprintf(b, "func %s(v *%s.%s, d *schema.ResourceData) error {\n",
		f.Function, sdkGo, f.Type)
	for _, a := range attributes {
		writeSet(b, a)
	}
	b.WriteString("return nil\n}\n")
}

func writeSet(b *bytes.Buffer, a attribute) {
	blocks := 0
	field := "v." + a.field
	value := "*" + field
	if a.enum != "" {
		value = fmt.Sprintf("string(%s)", field)
	}
	if a.optional {
		nonEmpty := fmt.Sprintf("%s != nil && *%s != \"\"", field, field)
		if a.enum != "" {
			nonEmpty = field + ` != ""`
		}
		fmt.Fprintf(b, "if %s {\n", nonEmpty)
		blocks++
	}
	if !a.computed {
		fmt.Fprintf(b, "if _, ok := d.GetOk(%q); ok || d.IsNewResource() {\n", a.name)
		blocks++
	}
	// A required attribute is set to "" when the response doesn't have it.
	if !a.optional && a.enum == "" {
		if blocks == 0 {
			b.WriteString("{\n")
			blocks++
		}
		fmt.Fprintf(b, "value := \"\"\nif %s != nil {\nvalue = *%s\n}\n", field, field)
		value = "value"
	}
	fmt.Fprintf(b, "if err := d.Set(%q, %s); err != nil {\nreturn err\n}\n", a.name, value)
	for range blocks {
		b.WriteString("}\n")
	}
}
